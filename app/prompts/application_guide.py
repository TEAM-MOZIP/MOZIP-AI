def build_user_content(
    application_instructions: str,
    required_documents_source: str | None,
) -> str:
    lines = [f"신청 방법 원문: {application_instructions}"]
    if required_documents_source:
        lines.append(f"필요 서류 원문: {required_documents_source}")
    return "\n".join(lines)
